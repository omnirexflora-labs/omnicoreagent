"""Generate the reference pages of the docs from the code.

    python scripts/generate_reference.py          # write them
    python scripts/generate_reference.py --check  # fail if they are stale

The reference cannot drift from the code because it is the code: every setting
from its dataclass and the comment above it, every method from its signature
and docstring, every CLI command from its definition, and the HTTP API from
OmniServe's own OpenAPI document. ``tests/test_reference_docs.py`` fails when
the committed pages differ from what this writes.
"""

