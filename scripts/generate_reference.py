# --- text ---------------------------------------------------------------------


def md(text: str) -> str:
    """Prose from a comment or docstring, safe in MDX: code spans kept, braces
    and angle brackets outside them escaped."""
    text = re.sub(r"``([^`]+)``", r"`\1`", text or "")
    parts = re.split(r"(`[^`]*`)", text)
    for i, part in enumerate(parts):
        if not part.startswith("`"):
            parts[i] = part.replace("{", "\\{").replace("}", "\\}").replace("<", "&lt;").replace(">", "&gt;")
    return "".join(parts).strip()


def code(value: str) -> str:
    """A value as an inline code span, in a table cell."""
    value = value.replace("|", "\\|")
    return f"`{value}`"


def first_paragraph(doc: str | None) -> str:
    doc = inspect.cleandoc(doc or "")
    return " ".join(doc.split("\n\n")[0].split()) if doc else ""


# --- settings -----------------------------------------------------------------


def _fields_with_comments(path: Path, class_name: str) -> list[dict[str, Any]]:
    """Each field of a dataclass with its type, declared default and the
    comment above it — or above the group of fields it belongs to."""
    source = path.read_text()
    lines = source.splitlines()
    tree = ast.parse(source)
    node = next(n for n in ast.walk(tree) if isinstance(n, ast.ClassDef) and n.name == class_name)
    fields, group_comment = [], None
    for stmt in node.body:
        if not (isinstance(stmt, ast.AnnAssign) and isinstance(stmt.target, ast.Name)):
            continue
        comment, i = [], stmt.lineno - 2
        while i >= 0 and lines[i].strip().startswith("#"):
            comment.insert(0, lines[i].strip().lstrip("#").strip())
            i -= 1
        if comment:
            group_comment = comment
        elif lines[stmt.lineno - 2].strip() == "":
            group_comment = None
        text = " ".join(line for line in (comment or group_comment or []) if line)
        if not text:
            raise SystemExit(f"{class_name}.{stmt.target.id} has no comment explaining it")
        fields.append(
            {
                "name": stmt.target.id,
                "type": ast.get_source_segment(source, stmt.annotation),
                "declared": ast.get_source_segment(source, stmt.value) if stmt.value else None,
                "doc": text,
            }
        )
    return fields


def _default(instance: Any, field: dict[str, Any]) -> str:
    declared = field["declared"] or ""
    if "default_factory" in declared:
        value = getattr(instance, field["name"])
        return json.dumps(value, sort_keys=True, default=str) if not isinstance(value, str) else repr(value)
    return declared


def settings_page(title: str, description: str, intro: str, path: Path, class_name: str, instance: Any, skip: set[str] = frozenset()) -> str:
    rows, details = [], []
    for field in _fields_with_comments(path, class_name):
        if field["name"] in skip:
            continue
        default = _default(instance, field)
        if len(default) > 40 and default.startswith(("{", "[")):
            # A structured default is readable only laid out.
            details += [
                f"### `{field['name']}`",
                "",
                md(field["doc"]),
                "",
                "```json",
                json.dumps(json.loads(default), indent=2, sort_keys=True),
                "```",
                "",
            ]
            shown = "see below"
        else:
            shown = code(default)
        rows.append(f"| {code(field['name'])} | {code(field['type'])} | {shown} | {md(field['doc'])} |")
    return "\n".join(
        [
            "---",
            f"title: {title}",
            f"description: '{description}'",
            "icon: 'sliders'",
            "---",
            "",
            NOTICE,
            "",
            f"# {title}",
            "",
            intro,
            "",
            "| Setting | Type | Default | What it does |",
            "|---|---|---|---|",
            *rows,
            "",
            *(["## Defaults in full", "", *details] if details else []),
        ]
    )


