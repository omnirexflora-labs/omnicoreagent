def openapi_document() -> str:
    os.environ.setdefault("LLM_API_KEY", "sk-reference-generation-only-0000")
    from omnicoreagent import OmniCoreAgent
    from omnicoreagent.serve.app_factory import create_omniserve_app
    from omnicoreagent.serve.config import OmniServeConfig

    agent = OmniCoreAgent(
        name="agent",
        system_instruction="Reference generation.",
        model_config={"provider": "openai", "model": "gpt-5.6-terra"},
    )
    app = create_omniserve_app(
        agent=agent,
        config=OmniServeConfig(),
        title="OmniServe",
        description=(
            "The HTTP API of an agent served with `omniserve run --agent agent.py`: runs, "
            "approvals, budgets, background tasks, sessions and the evidence of every run."
        ),
    )
    spec = app.openapi()
    # The document describes the API, not one build of it.
    spec["info"]["version"] = "latest"
    spec["servers"] = [{"url": "http://localhost:8000", "description": "omniserve run, locally"}]
    return json.dumps(spec, indent=2, sort_keys=True) + "\n"


